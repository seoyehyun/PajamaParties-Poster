#!/usr/bin/env python3
"""Write cixbuild .cfg files for the prefill and decode graphs made by export_qwen_onnx.py. Route A of docs/npu/npu-llm-plan.md.

  python make_cixbuild_cfg.py out_q05 --quant int8     # or int16
  (on the x86 PC, inside the NOE SDK container:)  cixbuild out_q05/cfg/prefill_build.cfg

Keys and values follow the build cfgs of CIX's own ai_model_hub examples (SDXL-Turbo: text_encoder, unet, vae_decoder), as
reported by a page fetch; I have not read them in the SDK itself. Things that are NOT confirmed are marked TODO in the
generated files and must be checked against the NOE SDK developer manual before the first build:
  - how several inputs are written in `input =` / `input_shape =` (the examples only have one input),
  - how `calibration_data` is given for several inputs (the examples use one .npy file),
  - the calibration array layout (this tool writes one .npy per input, shape (N, *input_shape[1:])).
The two presets differ in precision and therefore in NPU latency, so report which one was used:
  int8  = weight/activation/bias bits 8/8/32, per_tensor_asymmetric (the text_encoder example)
  int16 = 16/16/32, per_tensor_symmetric_full_range (the vae_decoder example); heavier, but INT8 is likely to hurt an LLM
"""
import argparse
import json
from pathlib import Path

QUANT = {
    "int8": dict(weight_bits=8, activation_bits=8, bias_bits=32, quantize_method_for_activation="per_tensor_asymmetric"),
    "int16": dict(weight_bits=16, activation_bits=16, bias_bits=32,
                  quantize_method_for_activation="per_tensor_symmetric_full_range"),
}


def shape_str(s):
    return "[" + ",".join(str(x) for x in s) + "]"


def cfg_text(name, graph, calib_dir, quant, target):
    ins = graph["inputs"]
    outs = list(graph["outputs"])
    q = QUANT[quant]
    lines = [
        f"# generated by make_cixbuild_cfg.py for {name}; keys copied from CIX ai_model_hub examples, see the script docstring",
        "[Common]",
        "mode=build",
        "",
        "[Parser]",
        "model_type = onnx",
        f"model_name = {name}",
        f"input_model = ./{graph['file']}",
        "# TODO(SDK manual): multi-input syntax. Comma-separated names and one shape per input is a guess.",
        f"input = {','.join(ins)}",
        f"input_shape = {';'.join(shape_str(s) for s in ins.values())}",
        f"output = {','.join(outs)}",
        "output_dir = ./out",
        "",
        "[Optimizer]",
        "dataset=NumpyDataset",
        "# TODO(SDK manual): calibration_data for several inputs. One .npy per input is written to the calib dir.",
        f"calibration_data = {','.join(f'./{calib_dir}/{n}.npy' for n in ins)}",
        "calibration_batch_size = 1",
        f"weight_bits = {q['weight_bits']}",
        f"activation_bits = {q['activation_bits']}",
        f"bias_bits = {q['bias_bits']}",
        "lut_items_in_bits = 8",
        f"quantize_method_for_activation={q['quantize_method_for_activation']}",
        "# Qwen uses RMSNorm, which export decomposes into Pow/ReduceMean/Sqrt/Div: the examples' [LayerNorm, Softmax] list",
        "# will not match RMSNorm. Keep Softmax in float16 and check what the SDK offers for the rest.",
        "trigger_float_op = disable & <[Softmax]:float16_preferred>",
        "cast_dtypes_for_lib = true",
        "dump = False",
        "dump_dir = ./out",
        "output_dir = ./out",
        "min_compatible_zhouyi_target = X2",
        "",
        "[GBuilder]",
        f"target = {target}",
        f"outputs = {name}.cix",
        "",
    ]
    return "\n".join(lines)


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("export_dir")
    ap.add_argument("--quant", choices=sorted(QUANT), default="int8")
    ap.add_argument("--target", default="X2_1204MP3", help="GBuilder target; three of the four hub examples use X2_1204MP3")
    args = ap.parse_args()
    d = Path(args.export_dir)
    meta = json.loads((d / "meta.json").read_text())
    (d / "cfg").mkdir(exist_ok=True)
    for key, calib in (("prefill", "calib_prefill"), ("decode", "calib_decode")):
        p = d / "cfg" / f"{key}_build.cfg"
        p.write_text(cfg_text(f"qwen_{key}", meta[key], calib, args.quant, args.target))
        print("wrote", p)
    print("run cixbuild from", d, "so the relative paths in the cfg resolve")


if __name__ == "__main__":
    main()
